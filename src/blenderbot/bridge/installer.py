_AUTO_ENSURED_PORTS: set[int] = set()


def install_blender_addon(
    *,
    target_extensions_dir: str | Path | None = None,
    target_startup_dir: str | Path | None = None,
    port: int = 18766,
) -> Path:
    """Install `blenderbot_bridge` into Blender 5.x's `extensions/user_default/` and `scripts/startup/`."""
    startup_root: Path | None = None
    if target_extensions_dir is None:
        inst = discover_blender()
        ext_root = Path(inst.user_extensions_dir)
        startup_root = (
            Path(target_startup_dir)
            if target_startup_dir is not None
            else Path(inst.user_scripts_startup_dir)
        )
    else:
        ext_root = Path(target_extensions_dir)
        if target_startup_dir is not None:
            startup_root = Path(target_startup_dir)

    addon_dir = ext_root / "blenderbot_bridge"
    addon_dir.mkdir(parents=True, exist_ok=True)

    blenderbot_src = str(Path(__file__).resolve().parents[2])
    manifest_path = addon_dir / "blender_manifest.toml"
    init_path = addon_dir / "__init__.py"
    init_text = INIT_PY_TEMPLATE.format(blenderbot_src=blenderbot_src, port=int(port))

    if not manifest_path.is_file() or manifest_path.read_text(encoding="utf-8") != MANIFEST_TOML:
        manifest_path.write_text(MANIFEST_TOML, encoding="utf-8")
    if not init_path.is_file() or init_path.read_text(encoding="utf-8") != init_text:
        init_path.write_text(init_text, encoding="utf-8")

    if startup_root is not None:
        startup_root.mkdir(parents=True, exist_ok=True)
        startup_path = startup_root / STARTUP_SCRIPT_NAME
        startup_text = STARTUP_PY_TEMPLATE.format(blenderbot_src=blenderbot_src, port=int(port))
        if not startup_path.is_file() or startup_path.read_text(encoding="utf-8") != startup_text:
            startup_path.write_text(startup_text, encoding="utf-8")

    return addon_dir


def ensure_blender_addon_installed(*, port: int = 18766) -> Path | None:
    """Idempotently ensure the Blender 5.x extension + GUI startup auto-bridge are installed."""
    p = int(port)
    if p in _AUTO_ENSURED_PORTS:
        return None
    inst = discover_blender()
    if not inst.ready:
        return None
    addon_dir = install_blender_addon(
        target_extensions_dir=inst.user_extensions_dir,
        target_startup_dir=inst.user_scripts_startup_dir,
        port=p,
    )
    _AUTO_ENSURED_PORTS.add(p)
    return addon_dir