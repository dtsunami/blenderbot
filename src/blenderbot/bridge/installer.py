"""Installs the Blender 5.x `blenderbot_bridge` Extension (`N`-panel UI + auto-start option)."""

from __future__ import annotations

from pathlib import Path

from blenderbot.config.blender_paths import discover_blender

MANIFEST_TOML = """schema_version = "1.0.0"

id = "blenderbot_bridge"
version = "0.1.0"
name = "blenderbot Bridge"
tagline = "Localhost TCP JSON-RPC bridge for blenderbot (stdlib only, zero cloud relay)"
maintainer = "blenderbot"
type = "add-on"
blender_version_min = "5.0.0"
license = ["SPDX:MIT"]
permissions = ["network", "files"]
"""

INIT_PY_TEMPLATE = '''"""blenderbot Bridge — Blender 5.x Extension (`View3D -> Sidebar (N) -> blenderbot`).

Auto-generated by `blenderbot --install-addon`. Zero third-party dependencies.
"""

from __future__ import annotations

import sys
import bpy

BLENDERBOT_SRC = {blenderbot_src!r}
DEFAULT_PORT = {port}

if BLENDERBOT_SRC not in sys.path:
    sys.path.insert(0, BLENDERBOT_SRC)


class BLENDERBOT_OT_start_bridge(bpy.types.Operator):
    bl_idname = "blenderbot.start_bridge"
    bl_label = "Connect blenderbot Bridge"
    bl_description = "Start localhost TCP bridge on 127.0.0.1 for blenderbot"

    def execute(self, _context):
        from blenderbot.bridge.server import start_in_blender_gui

        info = start_in_blender_gui(port=DEFAULT_PORT)
        self.report({{"INFO"}}, f"blenderbot listening on {{info.host}}:{{info.port}}")
        return {{"FINISHED"}}


class BLENDERBOT_OT_stop_bridge(bpy.types.Operator):
    bl_idname = "blenderbot.stop_bridge"
    bl_label = "Stop blenderbot Bridge"
    bl_description = "Stop the running localhost blenderbot TCP bridge"

    def execute(self, _context):
        from blenderbot.bridge.server import stop_in_blender_gui

        stop_in_blender_gui()
        self.report({{"INFO"}}, "blenderbot bridge stopped")
        return {{"FINISHED"}}


class BLENDERBOT_PT_panel(bpy.types.Panel):
    bl_label = "blenderbot"
    bl_idname = "BLENDERBOT_PT_panel"
    bl_space_type = "VIEW_3D"
    bl_region_type = "UI"
    bl_category = "blenderbot"

    def draw(self, _context):
        from blenderbot.bridge.server import get_gui_bridge_status

        layout = self.layout
        st = get_gui_bridge_status()
        if st.get("running"):
            box = layout.box()
            box.label(text=f"Connected: 127.0.0.1:{{st['port']}}", icon="CHECKMARK")
            box.label(text=f"Ops executed: {{st['ops_executed']}}")
            layout.operator("blenderbot.stop_bridge", icon="CANCEL")
        else:
            layout.label(text="Bridge stopped", icon="RADIOBUT_OFF")
            layout.operator("blenderbot.start_bridge", icon="PLAY")


CLASSES = (
    BLENDERBOT_OT_start_bridge,
    BLENDERBOT_OT_stop_bridge,
    BLENDERBOT_PT_panel,
)


def _auto_start_deferred():
    try:
        from blenderbot.bridge.server import get_gui_bridge_status, start_in_blender_gui

        if not get_gui_bridge_status().get("running"):
            start_in_blender_gui(port=DEFAULT_PORT)
    except Exception:
        pass
    return None


def register():
    for cls in CLASSES:
        bpy.utils.register_class(cls)
    if not bpy.app.background:
        bpy.app.timers.register(_auto_start_deferred, first_interval=0.25)


def unregister():
    try:
        from blenderbot.bridge.server import stop_in_blender_gui

        stop_in_blender_gui()
    except Exception:
        pass
    for cls in reversed(CLASSES):
        bpy.utils.unregister_class(cls)
'''


def install_blender_addon(
    *,
    target_extensions_dir: str | Path | None = None,
    port: int = 18766,
) -> Path:
    """Install `blenderbot_bridge` into Blender 5.x's `extensions/user_default/` folder."""
    if target_extensions_dir is None:
        inst = discover_blender()
        ext_root = Path(inst.user_extensions_dir)
    else:
        ext_root = Path(target_extensions_dir)

    addon_dir = ext_root / "blenderbot_bridge"
    addon_dir.mkdir(parents=True, exist_ok=True)

    blenderbot_src = str(Path(__file__).resolve().parents[2])
    (addon_dir / "blender_manifest.toml").write_text(MANIFEST_TOML, encoding="utf-8")
    (addon_dir / "__init__.py").write_text(
        INIT_PY_TEMPLATE.format(blenderbot_src=blenderbot_src, port=int(port)),
        encoding="utf-8",
    )
    return addon_dir